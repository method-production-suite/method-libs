//! The signature check, made the way the manifest format's own updater
//! makes it (tauri-plugin-updater 2.12.0: `verify_signature`,
//! `verify_signed_version`, `signed_version`, `base64_to_string`), with the
//! same minisign-verify release it links, so a signature the suite's
//! release pipelines make passes here exactly when it passed there.
//!
//! The public key and the signature both arrive as base64 of a minisign
//! "box" (an untrusted comment line, then the base64 key or signature, and
//! for a signature a trusted comment and its global signature). Legacy
//! (non-prehashed) signatures are allowed, as the format's updater allows
//! them.
//!
//! The trusted comment's `file:` field is NOT checked, on purpose: the
//! format's updater reads only `version:`, and the signature already covers
//! the archive's bytes, whatever the asset is called. `version:` is checked,
//! and [`crate::AppConfig::transport`] requires it
//! (`require_signed_version`), which is stricter than the format's default.
//! The test `the_file_field_is_not_checked` pins this.

use base64::Engine;
use minisign_verify::{PublicKey, Signature};
use semver::Version;
use std::str::FromStr;

/// What can be wrong with an update's signature, in words a person can be
/// shown.
#[derive(Clone, Debug, PartialEq, Eq)]
pub enum VerifyError {
    /// Not base64, or not UTF-8 inside.
    Encoding(String),
    /// minisign-verify refused the key, the signature, or the bytes.
    Minisign(String),
    /// The trusted comment names another version than the manifest.
    VersionMismatch { signed: String, announced: String },
    /// `require_signed_version` and the trusted comment names none.
    MissingVersion,
}

impl std::fmt::Display for VerifyError {
    fn fmt(&self, f: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
        match self {
            Self::Encoding(s) => write!(
                f,
                "The signature {s} could not be decoded, please check if it is a valid base64 string. The signature must be the contents of the `.sig` file generated by the Tauri bundler, as a string."
            ),
            Self::Minisign(s) => f.write_str(s),
            Self::VersionMismatch { signed, announced } => write!(
                f,
                "The update was signed for version {signed} but the update endpoint announced version {announced}. The endpoint response may have been tampered with to force installing a different release."
            ),
            Self::MissingVersion => f.write_str(
                "The update signature does not specify the version it was signed for, which `requireSignedVersion` requires. Re-sign and re-publish this release, or disable `requireSignedVersion`.",
            ),
        }
    }
}

impl std::error::Error for VerifyError {}

/// `base64_to_string`: standard alphabet, padded, then UTF-8.
pub fn base64_to_string(text: &str) -> Result<String, VerifyError> {
    let bytes = base64::engine::general_purpose::STANDARD
        .decode(text)
        .map_err(|e| VerifyError::Minisign(e.to_string()))?;
    String::from_utf8(bytes).map_err(|_| VerifyError::Encoding(text.into()))
}

/// The public key from base64 of its box: what every check trusts. A
/// placeholder key fails here, which is how an app knows it cannot update.
pub fn decode_public_key(pub_key: &str) -> Result<PublicKey, VerifyError> {
    PublicKey::decode(&base64_to_string(pub_key)?).map_err(|e| VerifyError::Minisign(e.to_string()))
}

/// The key id minisign prints, for a log line: the 8 bytes after the
/// algorithm, little-endian, as upper-case hex.
pub fn key_id(pubkey_b64: &str) -> Result<String, VerifyError> {
    let boxed = base64_to_string(pubkey_b64)?;
    let line = boxed
        .lines()
        .find(|l| !l.starts_with("untrusted comment:") && !l.trim().is_empty())
        .ok_or_else(|| VerifyError::Minisign("no key line".into()))?;
    let raw = base64::engine::general_purpose::STANDARD
        .decode(line.trim())
        .map_err(|e| VerifyError::Minisign(e.to_string()))?;
    if raw.len() != 42 {
        return Err(VerifyError::Minisign("not a minisign public key".into()));
    }
    Ok(raw[2..10]
        .iter()
        .rev()
        .map(|b| format!("{b:02X}"))
        .collect())
}

/// `verify_signature`: the bytes against the signature and the key, then
/// the signed version against the announced one. Returns the trusted
/// comment, which only now can be believed.
pub fn verify_signature(
    data: &[u8],
    release_signature: &str,
    pub_key: &str,
    announced_version: &str,
    require_signed_version: bool,
) -> Result<String, VerifyError> {
    let public_key = decode_public_key(pub_key)?;
    let signature = Signature::decode(&base64_to_string(release_signature)?)
        .map_err(|e| VerifyError::Minisign(e.to_string()))?;
    public_key
        .verify(data, &signature, true)
        .map_err(|e| VerifyError::Minisign(e.to_string()))?;
    verify_signed_version(
        signature.trusted_comment(),
        announced_version,
        require_signed_version,
    )?;
    Ok(signature.trusted_comment().to_string())
}

/// `verify_signed_version`: absent is fine unless required; present must
/// match as semver (`v` allowed), or literally when either is not semver.
pub fn verify_signed_version(
    trusted_comment: &str,
    announced_version: &str,
    require_signed_version: bool,
) -> Result<(), VerifyError> {
    let Some(signed) = signed_version(trusted_comment) else {
        return if require_signed_version {
            Err(VerifyError::MissingVersion)
        } else {
            Ok(())
        };
    };
    let matches = match (
        Version::from_str(signed.trim_start_matches('v')),
        Version::from_str(announced_version.trim_start_matches('v')),
    ) {
        (Ok(a), Ok(b)) => a == b,
        _ => signed == announced_version,
    };
    if matches {
        Ok(())
    } else {
        Err(VerifyError::VersionMismatch {
            signed: signed.into(),
            announced: announced_version.into(),
        })
    }
}

/// `signed_version`: the `version:` field of a tab-separated trusted
/// comment, as the suite's signers write it
/// (`timestamp:<t>\tfile:<name>\tversion:<v>`).
pub fn signed_version(trusted_comment: &str) -> Option<&str> {
    trusted_comment
        .split('\t')
        .find_map(|field| field.strip_prefix("version:"))
}

#[cfg(test)]
mod tests {
    use super::*;

    /// A suite app's published updater key, as its build config carries
    /// it: public data, used here as a real key in the real shape.
    const PUBLISHED: &str = "dW50cnVzdGVkIGNvbW1lbnQ6IG1pbmlzaWduIHB1YmxpYyBrZXk6IEU0RDA2NjhENTRGNkVCMzQKUldRMDYvWlVqV2JRNUQzRkpQMmVJZlQ4bTdaT2M5cmN2V05oVTJGdURUY0NwRDBRbEQ1c013UnYK";

    #[test]
    fn a_published_key_reads_and_has_its_id() {
        assert_eq!(key_id(PUBLISHED).unwrap(), "E4D0668D54F6EB34");
        assert!(decode_public_key(PUBLISHED).is_ok());
        assert!(decode_public_key("placeholder").is_err());
    }

    #[test]
    fn signed_version_rules_match_the_plugin() {
        // The format updater's own cases.
        assert_eq!(
            signed_version("timestamp:1700000000\tfile:app.tar.gz\tversion:1.2.3"),
            Some("1.2.3")
        );
        assert_eq!(
            signed_version("timestamp:1700000000\tfile:app.tar.gz"),
            None
        );
        assert!(verify_signed_version("version:v1.2.3", "1.2.3", false).is_ok());
        assert_eq!(
            verify_signed_version("version:1.2.2", "1.2.3", false).unwrap_err(),
            VerifyError::VersionMismatch {
                signed: "1.2.2".into(),
                announced: "1.2.3".into()
            }
        );
        assert!(verify_signed_version("file:x", "1.2.3", false).is_ok());
        assert_eq!(
            verify_signed_version("file:x", "1.2.3", true).unwrap_err(),
            VerifyError::MissingVersion
        );
        assert!(verify_signed_version("version:nightly", "nightly", false).is_ok());
        assert!(verify_signed_version("version:nightly", "Nightly", false).is_err());
    }

    #[test]
    fn the_file_field_is_not_checked() {
        // The format's updater reads `version:` alone (module docs).
        for comment in [
            "timestamp:1700000000\tfile:Method-Example-macOS.app.tar.gz\tversion:1.2.3",
            "timestamp:1700000000\tfile:something-else.tar.gz\tversion:1.2.3",
            "timestamp:1700000000\tversion:1.2.3",
        ] {
            assert!(
                verify_signed_version(comment, "1.2.3", true).is_ok(),
                "{comment}"
            );
        }
    }

    #[test]
    fn garbage_is_refused_in_words() {
        assert!(verify_signature(b"x", "!!!", PUBLISHED, "1.0.0", false).is_err());
        assert!(verify_signature(b"x", "c2ln", PUBLISHED, "1.0.0", false).is_err());
    }
}
